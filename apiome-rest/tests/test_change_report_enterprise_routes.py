def test_creator_submits_a_draft_for_review(mdb):
    mdb.get_change_report_by_published_revision.return_value = _report()
    mdb.transition_change_report_approval.return_value = _report(**_PENDING)

    r = client.post(f"{_BASE}/submit")

    assert r.status_code == 200
    body = r.json()
    assert body["approvalState"] == "pending_review"
    assert body["submittedBy"] == "user-a"
    args, kwargs = mdb.transition_change_report_approval.call_args
    assert args == ("v1", "t1", "p1")
    assert kwargs == {
        "from_state": "draft",
        "to_state": "pending_review",
        "actor_id": "user-a",
        "review_note": None,
    }
    action, audit = _audit_call(mdb)
    assert action == ACTION_REPORT_SUBMIT
    assert audit["actor_id"] == "user-a"
    assert audit["change_report_id"] == "cr-1"
    assert audit["published_revision_id"] == "v1"
    assert audit["detail"] == {"from": "draft", "to": "pending_review", "note": None}


