"""GVM-3.5 (#5873) — the ``fix`` fixture kind of the scanner-evaluation corpus and its CI gates.

Every fixable rule has a one-defect fixture under ``tests/fixtures/scanner_evaluation/fix/<rule>/``
(the document, the expected plan, the expected post-fix document). Gates, per fixture:

1. after the fix the rule is clean;
2. the finding set outside the rule is unchanged;
3. planning and applying twice is byte-stable (and the plan is the expected one);
4. the classified diff of the fix is non-breaking (or pinned breaking with a stated reason —
   the plan then withholds it);
5. a rule flagged ``fixable`` without a fixture fails :func:`test_every_fixable_rule_has_a_fixture`
   (and a fixture or manifest entry without a fixable rule fails too).

The corpus README's fixable table is regenerated by ``scripts/generate_fix_corpus_readme.py``;
:func:`test_readme_fixable_table_is_current` fails when it is stale.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Set, Tuple

import pytest

from app.lint_fix import FixOptions, apply_fix_ops
from app.lint_fix_plan import STATUS_BREAKING, STATUS_READY, build_fix_plan
from app.lint_rule_registry import builtin_rule_descriptors
from app.scanner_evaluation_corpus import (
    corpus_root,
    fix_fixture_findings,
    fix_fixture_ids,
    fixable_findings,
    fixable_rules_table,
    load_fixture,
    load_manifest,
    plan_fixable,
    run_fixture,
)

TABLE_BEGIN = "<!-- fixable-rules:begin -->"
TABLE_END = "<!-- fixable-rules:end -->"


def _load(rule_id: str) -> Dict[str, Any]:
    return load_fixture(f"fix/{rule_id}")


def _options(fixture: Dict[str, Any]) -> FixOptions:
    raw = fixture.get("options") or {}
    return FixOptions(
        operation_id_template=raw.get("operationIdTemplate", FixOptions().operation_id_template),
        opt_in=frozenset(raw.get("optIn", [])),
    )


def _findings_outside(document: Dict[str, Any], rule_id: str) -> Set[Tuple[str, str, str]]:
    return {
        (f.rule, f.path, f.message) for f in fix_fixture_findings(document) if f.rule != rule_id
    }


def _fix_once(document: Dict[str, Any], rule_id: str, options: FixOptions) -> Dict[str, Any]:
    for finding in fixable_findings(document):
        if finding.rule == rule_id:
            document = apply_fix_ops(document, plan_fixable(document, finding, options))
    return document


IDS: List[str] = fix_fixture_ids()


def test_every_fixable_rule_has_a_fixture():
    """Gate 5: a rule flagged fixable without a fixture fails the build."""
    fixable = {d.rule_id for d in builtin_rule_descriptors() if d.fixable}
    on_disk = {p.parent.name for p in (corpus_root() / "fix").glob("*/fixture.json")}
    assert fixable == set(IDS) == on_disk, (
        f"fixable without a fixture: {sorted(fixable - on_disk)}; "
        f"fixable without a manifest entry: {sorted(fixable - set(IDS))}; "
        f"fixture without a fixable rule: {sorted((on_disk | set(IDS)) - fixable)}; "
        f"fixture not in the manifest: {sorted(on_disk - set(IDS))}"
    )


@pytest.mark.parametrize("rule_id", IDS)
def test_fixture_declares_its_kind_and_one_defect(rule_id: str):
    fixture = _load(rule_id)
    assert fixture["kind"] == "fix" and fixture["id"] == f"fix/{rule_id}"
    assert fixture["rule"] == rule_id
    findings = fixable_findings(fixture["before"])
    assert [f.rule for f in findings] == [rule_id], "a fix fixture carries one defect"
    assert {"path": findings[0].path, "message": findings[0].message} == fixture["finding"]
    blocking, run_findings = run_fixture(fixture)
    assert blocking == set()
    assert rule_id in {f["rule"] for f in run_findings}


@pytest.mark.parametrize("rule_id", IDS)
def test_gate1_after_the_fix_the_rule_is_clean(rule_id: str):
    fixture = _load(rule_id)
    after = _fix_once(fixture["before"], rule_id, _options(fixture))
    assert json.dumps(after) == json.dumps(fixture["after"])  # key order is part of the document
    assert all(f.rule != rule_id for f in fix_fixture_findings(after))


@pytest.mark.parametrize("rule_id", IDS)
def test_gate2_no_other_finding_changes(rule_id: str):
    fixture = _load(rule_id)
    after = _fix_once(fixture["before"], rule_id, _options(fixture))
    assert _findings_outside(after, rule_id) == _findings_outside(fixture["before"], rule_id)


@pytest.mark.parametrize("rule_id", IDS)
def test_gate3_planning_and_applying_twice_is_byte_stable(rule_id: str):
    fixture = _load(rule_id)
    options = _options(fixture)
    before = fixture["before"]
    ops = plan_fixable(before, fixable_findings(before)[0], options)
    assert [op.as_dict() for op in ops] == fixture["plan"]
    once = _fix_once(before, rule_id, options)
    twice = _fix_once(once, rule_id, options)
    assert json.dumps(twice) == json.dumps(once) == json.dumps(fixture["after"])
    # The whole-plan path is stable too: the same document plans to the same entries, twice.
    template = (fixture.get("options") or {}).get("operationIdTemplate", FixOptions().operation_id_template)
    plans = [build_fix_plan(before, rules=[rule_id], operation_id_template=template) for _ in range(2)]
    assert json.dumps(plans[0].as_dict()) == json.dumps(plans[1].as_dict())
    assert [op.as_dict() for op in plans[0].entries[0].ops] == fixture["plan"]
    if fixture["classification"]["planStatus"] == STATUS_READY:
        assert plans[0].patch() == fixture["plan"]
        assert json.dumps(plans[0].fixed_document) == json.dumps(fixture["after"])
    else:  # a withheld fix is never applied by the plan
        assert plans[0].patch() == []


@pytest.mark.parametrize("rule_id", IDS)
def test_gate4_the_classified_diff_of_the_fix_is_non_breaking(rule_id: str):
    """The fix's classified delta is non-breaking, or the fixture says why the plan withholds it.

    The classifier reads a few mechanically safe edits as breaking (a ``nullable`` → type-array
    move, a server URL spelling). Those fixtures pin ``classification`` with a ``reason``; the
    gate holds the classifier to it, so a fix cannot become breaking — or stop being withheld —
    without the fixture changing in review.
    """
    fixture = _load(rule_id)
    expected = fixture["classification"]
    template = (fixture.get("options") or {}).get("operationIdTemplate", FixOptions().operation_id_template)
    plan = build_fix_plan(fixture["before"], rules=[rule_id], operation_id_template=template)
    assert [e.rule_id for e in plan.entries] == [rule_id]
    entry = plan.entries[0]
    assert entry.classification is not None
    assert entry.classification["maxSeverity"] == expected["maxSeverity"]
    assert entry.status == expected["planStatus"]
    if expected["maxSeverity"] == "breaking":
        assert entry.status == STATUS_BREAKING
        assert expected.get("reason", "").strip(), f"{rule_id}: a breaking fix fixture needs a reason"
    else:
        assert entry.status == STATUS_READY and "reason" not in expected


def test_manifest_lists_each_fix_fixture_once_and_expects_its_rule():
    entries = [e for e in load_manifest()["fixtures"] if e.get("kind") == "fix"]
    assert len(entries) == len({e["id"] for e in entries}) == len(IDS)
    for entry in entries:
        rule_id = entry["id"].split("/", 1)[1]
        assert entry["expected_rule_ids"] == [rule_id]
        assert entry["expected_blocking_rule_ids"] == []


def test_readme_fixable_table_is_current():
    readme = (corpus_root() / "README.md").read_text(encoding="utf-8")
    assert TABLE_BEGIN in readme and TABLE_END in readme
    block = readme.split(TABLE_BEGIN, 1)[1].split(TABLE_END, 1)[0]
    assert block.strip("\n") == fixable_rules_table().strip("\n"), (
        "corpus README fixable table is stale — run `uv run python scripts/generate_fix_corpus_readme.py`"
    )
