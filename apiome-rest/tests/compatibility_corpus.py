def _mark(answer: Optional[Dict[str, Any]]) -> str:
    if answer is None:
        return "—"
    return "✓" if answer.get("compatible") else "✗"


def render_waiver_table(waivers: Sequence[Dict[str, Any]]) -> str:
    """The Markdown table of documented differences (README and docs page)."""
    if not waivers:
        return "No known differences: every corpus verdict matches its reference tool.\n"
    titles = {tool.id: tool.title for spec in FORMATS.values() for tool in spec.references}
    lines = ["| Case | Reference tool | Modes | Why Apiome differs |", "| --- | --- | --- | --- |"]
    for waiver in waivers:
        lines.append(
            f"| `{waiver['case']}` | {titles.get(waiver['tool'], waiver['tool'])} | "
            f"{', '.join(f'`{m}`' for m in waiver['modes'])} | {waiver['reason']} |"
        )
    return "\n".join(lines) + "\n"


def render_readme(cases: Sequence[Case], waivers: Sequence[Dict[str, Any]]) -> str:
    """The generated corpus README: layout, regeneration, every case's verdicts, the waivers."""
    out = [
        "# Cross-format compatibility golden corpus",
        "",
        "<!-- Generated by tests/compatibility_corpus.py (XPC-4.6, #5750). Do not edit by hand: run",
        "     `uv run pytest tests/test_compatibility_corpus_golden.py --update-golden`. -->",
        "",
        "Fixture pairs per format with Apiome's expected verdict under every compatibility mode,",
        "cross-checked against the reference tool each format's teams already run. A verdict that",
        "differs from the reference tool's is a `reference_disagreement` and fails the build unless",
        "`waivers.json` documents why.",
        "",
        "## Layout",
        "",
        "- `<format>/<case>/base.<ext>` and `head.<ext>` — the two versions (`base/` and `head/`",
        "  directories of `.proto` files for Protobuf).",
        "- `<format>/<case>/expected.json` — `description` and `source` (hand-written), `verdicts`",
        "  (Apiome's grade per mode, regenerated) and `references` (each reference tool's recorded",
        "  verdict per mode).",
        "- `waivers.json` — the known differences, each with its reason.",
        "",
        "## Running and regenerating",
        "",
        "```bash",
        "uv run pytest tests/test_compatibility_corpus_golden.py            # compare",
        "uv run pytest tests/test_compatibility_corpus_golden.py --update-golden  # regenerate",
        "```",
        "",
        "Regenerating rewrites every `verdicts`, re-records the references of every tool available",
        "live, keeps the recordings of the rest, prunes case directories missing a side and rewrites",
        "this README and the docs page's waiver table. Reference tools run live when present:",
        "",
        "- `buf` (`./scripts/install_dev_toolchain.sh buf`); Protobuf cases need it to compile.",
        "- `graphql-inspector-diff` and `asyncapi-diff` (on `PATH`, in `.tools/bin`, or named by",
        "  `APIOME_GRAPHQL_INSPECTOR_DIFF_BIN` / `APIOME_ASYNCAPI_DIFF_BIN`).",
        f"- A registry's Confluent-compatible API: `{APICURIO_URL_ENV}` (e.g.",
        "  `http://localhost:8080/apis/ccompat/v7` for `apicurio/apicurio-registry`) and",
        f"  `{CONFLUENT_URL_ENV}`.",
        "",
        f"`{STRICT_ENV}=1` (or a comma-separated list of tool ids) fails the run when a named reference",
        f"tool is missing instead of skipping its live check; `{REPORT_ENV}=<path>`",
        "writes the run's findings as JSON.",
        "",
        "## Formats",
        "",
        "| Format | Graded under | Reference tools | Cases |",
        "| --- | --- | --- | ---: |",
    ]
    for spec in FORMATS.values():
        count = sum(1 for c in cases if c.format == spec.key)
        tools = ", ".join(t.title for t in spec.references)
        out.append(f"| {spec.title} | {', '.join(f'`{m}`' for m in spec.modes)} | {tools} | {count} |")
    out += [
        "",
        "`@asyncapi/diff` has no modes: its verdict is compared with Apiome's default (`BACKWARD`),",
        "and a diff it leaves `unclassified` is not compared. GraphQL has no modes either.",
        "",
    ]
    for spec in FORMATS.values():
        format_cases = [c for c in cases if c.format == spec.key]
        if not format_cases:
            continue
        out += [f"## {spec.title}", ""]
        header = "| Case | " + " | ".join(f"`{m}`" for m in spec.modes) + " | Reference agrees | Source |"
        out += [header, "| --- |" + " :---: |" * len(spec.modes) + " --- | --- |"]
        for case in format_cases:
            expected = read_expected(case)
            verdicts = expected.get("verdicts", {})
            references = expected.get("references", {})
            agreement = []
            for tool, recording in sorted(references.items()):
                diff = [
                    m
                    for m, a in sorted(recording.get("verdicts", {}).items())
                    if a.get("compatible") is not None
                    and m in verdicts
                    and bool(a["compatible"]) != bool(verdicts[m]["compatible"])
                ]
                agreement.append(f"{tool}: {'waived ' + ', '.join(diff) if diff else 'yes'}")
            cells = " | ".join(_mark(verdicts.get(m)) for m in spec.modes)
            description = expected.get("description", "")
            source = expected.get("source", "")
            out.append(f"| `{case.name}` — {description} | {cells} | {'; '.join(agreement) or '—'} | {source} |")
        out.append("")
    out += ["## Known differences (waivers)", "", render_waiver_table(waivers).rstrip("\n"), ""]
    return "\n".join(out)


def replace_docs_section(page: str, waivers: Sequence[Dict[str, Any]]) -> str:
    """``page`` with the text between :data:`DOCS_START` and :data:`DOCS_END` regenerated.

    Raises:
        ValueError: If the page lacks the markers.
    """
    if DOCS_START not in page or DOCS_END not in page:
        raise ValueError(f"{DOCS_PAGE} lacks the compatibility-reference-waivers markers")
    head, rest = page.split(DOCS_START, 1)
    _, tail = rest.split(DOCS_END, 1)
    return f"{head}{DOCS_START}\n\n{render_waiver_table(waivers)}\n{DOCS_END}{tail}"
