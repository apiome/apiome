def _proto_files(side: Side) -> List[Any]:
    from app.proto_descriptor import ProtoFile

    return [ProtoFile(path=path, content=text) for path, text in sorted(side.files.items())]


def _proto_model(side: Side) -> CanonicalApi:
    """Compile a Protobuf side with ``buf build`` and normalize its target files."""
    from google.protobuf import descriptor_pb2

    from app.proto_descriptor import compile_proto_descriptor_set
    from app.proto_normalizer import ProtoNormalizer

    compiled = _run(compile_proto_descriptor_set(_proto_files(side)))
    targets = {f.name for f in compiled.target_files}
    out = descriptor_pb2.FileDescriptorSet()
    out.file.extend(f for f in compiled.proto.file if f.name in targets)
    return ProtoNormalizer().normalize(out.SerializeToString(deterministic=True))


@functools.lru_cache(maxsize=None)
def _models_by_id(case_id: str) -> Tuple[CanonicalApi, CanonicalApi]:
    case = next(c for c in load_cases() if c.id == case_id)
    spec = FORMATS[case.format]
    if spec.key == "protobuf":
        return _proto_model(case.base), _proto_model(case.head)
    if spec.key == "asyncapi":
        # The corpus documents are already in the dereferenced shape the AsyncAPI parser hands the
        # normalizer. They go to the normalizer directly (as the XPC-4.4 suite does) because the
        # bundled parser rejects an Avro ``schemaFormat`` payload, which two cases exercise.
        from app.asyncapi_normalizer import AsyncApiNormalizer

        return (
            AsyncApiNormalizer().normalize(json.loads(case.base.text)),
            AsyncApiNormalizer().normalize(json.loads(case.head.text)),
        )
    return (
        parse_candidate(spec.source_format, case.base.text, source_label=case.base.label),
        parse_candidate(spec.source_format, case.head.text, source_label=case.head.label),
    )


def canonical_models(case: Case) -> Tuple[CanonicalApi, CanonicalApi]:
    """The base and head canonical models, through the importer the compatibility API uses.

    Raises:
        ReferenceUnavailableError: For a Protobuf case when ``buf`` (which compiles it) is missing.
    """
    if case.format == "protobuf":
        from app.proto_descriptor import BUF_TOOL_KEY

        _probe(BUF_TOOL_KEY)
    return _models_by_id(case.id)


def _policy(spec: FormatSpec, mode: str) -> CompatibilityPolicy:
    if spec.key == "protobuf":
        return CompatibilityPolicy(category=mode)
    if mode == DEFAULT_MODE:
        return CompatibilityPolicy()
    return CompatibilityPolicy(mode=mode)


def _rule_ids(result: ClassificationResult) -> List[str]:
    return sorted({c.rule_id for c in result.classifications} | {f.rule_id for f in result.unattributed})


def apiome_verdicts(case: Case) -> Dict[str, Dict[str, Any]]:
    """Grade a case under every mode of its format with :func:`classify_under` — the same path
    the classified diff and the compatibility API take.

    Returns:
        ``{mode: {"compatible": bool, "severity": str, "rule_ids": [str]}}``.
    """
    spec = FORMATS[case.format]
    base, head = canonical_models(case)
    out: Dict[str, Dict[str, Any]] = {}
    for mode in spec.modes:
        result, _ = classify_under(base, head, _policy(spec, mode))
        severity = result.overall_severity.value
        out[mode] = {"compatible": severity != "breaking", "severity": severity, "rule_ids": _rule_ids(result)}
    return out


