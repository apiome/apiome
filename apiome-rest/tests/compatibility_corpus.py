def _waiver_index(waivers: Sequence[Dict[str, Any]]) -> Dict[Tuple[str, str, str], str]:
    return {(w["case"], w["tool"], mode): w["reason"] for w in waivers for mode in w["modes"]}


def disagreements(
    case: Case,
    verdicts: Dict[str, Dict[str, Any]],
    references: Dict[str, Dict[str, Any]],
    waivers: Sequence[Dict[str, Any]],
) -> List[Finding]:
    """Every ``(tool, mode)`` where a reference verdict differs from Apiome's.

    Args:
        case: The case.
        verdicts: Apiome's verdicts (:func:`apiome_verdicts`).
        references: ``{tool id: {"version": str, "verdicts": {mode: {"compatible": …}}}}``.
        waivers: The documented differences.

    Returns:
        The findings, each carrying its waiver's reason when one covers it.
    """
    index = _waiver_index(waivers)
    findings = []
    for tool, recording in sorted(references.items()):
        for mode, answer in sorted(recording.get("verdicts", {}).items()):
            reference = answer.get("compatible")
            if reference is None or mode not in verdicts:
                continue
            apiome = bool(verdicts[mode]["compatible"])
            if apiome != bool(reference):
                findings.append(Finding(case.id, tool, mode, apiome, bool(reference), index.get((case.id, tool, mode))))
    return findings


def live_references(case: Case) -> Tuple[Dict[str, Dict[str, Any]], Dict[str, str]]:
    """Run every reference tool of the case's format that is available.

    Returns:
        ``(recordings, unavailable)``: ``{tool id: {"version", "verdicts"}}`` for the tools that
        ran, and ``{tool id: reason}`` for the ones that could not.
    """
    ran: Dict[str, Dict[str, Any]] = {}
    unavailable: Dict[str, str] = {}
    for tool in FORMATS[case.format].references:
        try:
            version, verdicts = tool.run(case)
        except ReferenceUnavailableError as exc:
            unavailable[tool.id] = str(exc)
            continue
        ran[tool.id] = {"version": version, "verdicts": verdicts}
    return ran, unavailable


def comparable(recording: Dict[str, Any]) -> Dict[str, Optional[bool]]:
    """A recording's verdicts reduced to ``{mode: compatible}`` (versions and detail ignored)."""
    return {mode: answer.get("compatible") for mode, answer in recording.get("verdicts", {}).items()}


