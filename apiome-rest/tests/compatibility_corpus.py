def should_update(request: Any) -> bool:
    """Whether this run regenerates the corpus (``--update-golden`` or :data:`UPDATE_ENV`)."""
    if os.environ.get(UPDATE_ENV, "").strip() == "1":
        return True
    return bool(request.config.getoption("--update-golden", default=False))


def is_strict(tool_id: str) -> bool:
    """Whether ``tool_id`` must be available in this run (:data:`STRICT_ENV`).

    Args:
        tool_id: A reference tool id.

    Returns:
        ``True`` when :data:`STRICT_ENV` is ``1`` or lists ``tool_id``.
    """
    raw = os.environ.get(STRICT_ENV, "").strip()
    return raw == "1" or tool_id in {part.strip() for part in raw.split(",")}


def build_expected(case: Case, previous: Dict[str, Any], live: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """The regenerated ``expected.json`` for a case.

    Args:
        case: The case.
        previous: Its current ``expected.json`` (``{}`` when new); ``description`` and ``source``
            are kept, and so is the recording of every tool that did not run live.
        live: The recordings of the tools that ran live this time.

    Returns:
        The document to write.
    """
    references = dict(previous.get("references") or {})
    references.update(live)
    return {
        "case": case.id,
        "description": previous.get("description", ""),
        "source": previous.get("source", ""),
        "verdicts": apiome_verdicts(case),
        "references": {tool: references[tool] for tool in sorted(references)},
    }


def write_json(path: Path, document: Dict[str, Any]) -> None:
    """Write a corpus JSON file in its canonical layout."""
    path.write_text(json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def prune_orphans() -> List[Path]:
    """Delete case directories that no longer hold both sides; returns what was removed."""
    removed = orphan_dirs()
    for directory in removed:
        shutil.rmtree(directory)
    return removed


