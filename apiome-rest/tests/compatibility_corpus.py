class ReferenceUnavailableError(Exception):
    """A reference tool is not installed or not reachable in this run."""


@dataclass(frozen=True)
class Side:
    """One version of a case: its files, keyed by path relative to the side.

    Attributes:
        files: ``{relative path: text}``; one entry except for a Protobuf side.
        label: The file name a single-file importer sees.
    """

    files: Dict[str, str]
    label: str

    @property
    def text(self) -> str:
        """The single file's text."""
        (only,) = self.files.values()
        return only


@dataclass(frozen=True)
class Case:
    """One corpus case.

    Attributes:
        format: The format directory (``avro``, ``protobuf``, …).
        name: The case directory name.
        path: The case directory.
        base: The earlier version.
        head: The later version.
    """

    format: str
    name: str
    path: Path
    base: Side
    head: Side

    @property
    def id(self) -> str:
        """``<format>/<case>``, the id waivers and reports use."""
        return f"{self.format}/{self.name}"

    @property
    def expected_path(self) -> Path:
        """The case's ``expected.json``."""
        return self.path / "expected.json"


@dataclass(frozen=True)
class ReferenceTool:
    """A reference tool a format's verdicts are cross-checked against.

    Attributes:
        id: The tool id recorded under ``references`` (``buf``, ``apicurio-registry``, …).
        title: How the README and docs name it.
        modes: The Apiome modes its verdict is compared with.
        run: ``run(case) -> (version, {mode: {"compatible": bool | None, "detail": [str]}})``;
            raises :class:`ReferenceUnavailableError` when the tool cannot be used in this run.
        required: Whether every case of the format must carry a recording of this tool (the
            Confluent registry is optional: only the cases recorded against one carry it).
    """

    id: str
    title: str
    modes: Tuple[str, ...]
    run: Callable[["Case"], Tuple[str, Dict[str, Dict[str, Any]]]]
    required: bool = True


@dataclass(frozen=True)
class FormatSpec:
    """How one format's cases are read, graded and cross-checked.

    Attributes:
        key: The format directory name.
        title: The heading the README uses.
        source_format: The importer key :func:`app.compatibility_modes.parse_candidate` reads.
        extension: The ``base`` / ``head`` file extension (``""`` for directory sides).
        modes: The modes (or Protobuf categories) every case is graded under.
        references: The reference tools.
    """

    key: str
    title: str
    source_format: str
    extension: str
    modes: Tuple[str, ...]
    references: Tuple[ReferenceTool, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class Finding:
    """One reference disagreement.

    Attributes:
        case: ``<format>/<case>``.
        tool: The reference tool id.
        mode: The mode or category.
        apiome_compatible: Apiome's verdict.
        reference_compatible: The tool's verdict.
        waiver: The documented reason, when a waiver covers it.
    """

    case: str
    tool: str
    mode: str
    apiome_compatible: bool
    reference_compatible: bool
    waiver: Optional[str] = None

    def as_dict(self) -> Dict[str, Any]:
        """The finding as it is written to the report."""
        return {
            "kind": REFERENCE_DISAGREEMENT,
            "case": self.case,
            "tool": self.tool,
            "mode": self.mode,
            "apiome": "compatible" if self.apiome_compatible else "incompatible",
            "reference": "compatible" if self.reference_compatible else "incompatible",
            "waived": self.waiver is not None,
            "reason": self.waiver,
        }


