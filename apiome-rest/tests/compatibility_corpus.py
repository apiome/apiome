def _read_side(case_dir: Path, side: str, spec: FormatSpec) -> Optional[Side]:
    """Read ``base`` / ``head`` of a case, or ``None`` when it is missing."""
    if not spec.extension:
        root = case_dir / side
        if not root.is_dir():
            return None
        files = {p.relative_to(root).as_posix(): p.read_text(encoding="utf-8") for p in sorted(root.rglob("*.proto"))}
        return Side(files=files, label=side) if files else None
    path = case_dir / f"{side}{spec.extension}"
    if not path.is_file():
        return None
    return Side(files={path.name: path.read_text(encoding="utf-8")}, label=path.name)


def case_dirs() -> List[Tuple[FormatSpec, Path]]:
    """Every case directory under a known format, sorted."""
    out = []
    for key, spec in sorted(FORMATS.items()):
        root = CORPUS_ROOT / key
        if root.is_dir():
            out.extend((spec, d) for d in sorted(root.iterdir()) if d.is_dir())
    return out


def load_cases() -> List[Case]:
    """Every complete case (both sides present), sorted by id."""
    cases = []
    for spec, case_dir in case_dirs():
        base, head = _read_side(case_dir, "base", spec), _read_side(case_dir, "head", spec)
        if base is not None and head is not None:
            cases.append(Case(format=spec.key, name=case_dir.name, path=case_dir, base=base, head=head))
    return cases


def orphan_dirs() -> List[Path]:
    """Case directories missing a side — pruned by ``--update-golden``."""
    return [d for spec, d in case_dirs() if _read_side(d, "base", spec) is None or _read_side(d, "head", spec) is None]


def read_expected(case: Case) -> Dict[str, Any]:
    """The case's ``expected.json``, or ``{}`` when it has none yet."""
    if not case.expected_path.is_file():
        return {}
    return json.loads(case.expected_path.read_text(encoding="utf-8"))


def load_waivers() -> List[Dict[str, Any]]:
    """The documented differences, in file order."""
    return list(json.loads(WAIVERS_PATH.read_text(encoding="utf-8")).get("waivers", []))


