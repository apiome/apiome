def _run(coro: Any) -> Any:
    """Run one coroutine to completion (the corpus is driven from sync tests)."""
    return asyncio.run(coro)


def _registry_reference(
    tool_id: str, title: str, env: str, schema_type: str, *, required: bool = True
) -> ReferenceTool:
    """A Confluent-compatible registry (Confluent Schema Registry, Apicurio's ``ccompat`` API).

    For every mode it uses a throwaway subject: sets it to ``NONE``, registers the base, sets the
    mode, then asks ``POST /compatibility/subjects/{subject}/versions?verbose=true`` about the head
    — the registry's dry-run check, which registers nothing.

    Args:
        tool_id: The id recorded under ``references``.
        title: The README title.
        env: The environment variable naming the registry's base URL.
        schema_type: ``AVRO`` or ``JSON``.
        required: Whether every case of the format must carry its recording.

    Returns:
        The :class:`ReferenceTool`.
    """

    def run(case: Case) -> Tuple[str, Dict[str, Dict[str, Any]]]:
        import httpx

        url = os.environ.get(env, "").strip().rstrip("/")
        if not url:
            raise ReferenceUnavailableError(f"{env} is not set")
        headers = {"Content-Type": "application/vnd.schemaregistry.v1+json"}
        verdicts: Dict[str, Dict[str, Any]] = {}
        try:
            with httpx.Client(base_url=url, timeout=30, headers=headers) as client:

                def call(method: str, path: str, body: Any = None) -> Any:
                    response = client.request(method, path, json=body)
                    if response.status_code >= 400 and response.status_code != 404:
                        raise AssertionError(f"{method} {path} → {response.status_code}: {response.text}")
                    return response.json() if response.content else None

                for mode in REGISTRY_MODES:
                    subject = f"apiome-corpus--{case.format}--{case.name}--{mode.lower()}"
                    call("DELETE", f"/subjects/{subject}")
                    call("DELETE", f"/subjects/{subject}?permanent=true")
                    call("PUT", f"/config/{subject}", {"compatibility": "NONE"})
                    call("POST", f"/subjects/{subject}/versions", {"schemaType": schema_type, "schema": case.base.text})
                    call("PUT", f"/config/{subject}", {"compatibility": mode})
                    answer = call(
                        "POST",
                        f"/compatibility/subjects/{subject}/versions?verbose=true",
                        {"schemaType": schema_type, "schema": case.head.text},
                    )
                    verdicts[mode] = {
                        "compatible": bool(answer["is_compatible"]),
                        "detail": _registry_detail(answer.get("messages") or []),
                    }
                version = _registry_version(client, url)
        except httpx.HTTPError as exc:
            raise ReferenceUnavailableError(f"{tool_id} at {url} is not reachable: {exc}") from exc
        return version, verdicts

    return ReferenceTool(id=tool_id, title=title, modes=REGISTRY_MODES, run=run, required=required)


def _registry_detail(messages: Sequence[Any]) -> List[str]:
    """The ``errorType`` names a registry's verbose messages carry, in order, without duplicates."""
    out: List[str] = []
    for message in messages:
        text = str(message)
        if "errorType:'" in text:
            name = text.split("errorType:'", 1)[1].split("'", 1)[0]
            if name not in out:
                out.append(name)
    return out


def _registry_version(client: Any, url: str) -> str:
    """The registry's version: Confluent's ``/v1/metadata/version``, or Apicurio's system info."""
    try:
        if "/apis/ccompat/" in url:
            info = client.get(url.split("/apis/ccompat/", 1)[0] + "/apis/registry/v3/system/info").json()
        else:
            info = client.get("/v1/metadata/version").json()
        return str(info.get("version") or "unknown")
    except Exception:  # noqa: BLE001 - a version is informational only
        return "unknown"


def _probe(tool_key: str) -> str:
    """The pinned version of a bundled tool, or :class:`ReferenceUnavailableError` when it is missing."""
    from app.toolchain_packaging import probe_tool

    probe = probe_tool(tool_key)
    if not getattr(probe, "available", False):
        raise ReferenceUnavailableError(f"{tool_key} is not installed ({getattr(probe, 'detail', '')})")
    return str(probe.pinned_version)


def _buf_run(case: Case) -> Tuple[str, Dict[str, Dict[str, Any]]]:
    """``buf breaking`` at each of the four categories."""
    from app.proto_breaking import BufBreakingStrictness, run_buf_breaking
    from app.proto_descriptor import BUF_TOOL_KEY

    version = _probe(BUF_TOOL_KEY)
    verdicts: Dict[str, Dict[str, Any]] = {}
    for category in PROTOBUF_CATEGORIES:
        result = _run(
            run_buf_breaking(
                _proto_files(case.head), _proto_files(case.base), strictness=BufBreakingStrictness(category)
            )
        )
        rules = sorted({change.rule.rsplit(".", 1)[-1].upper() for change in result.changes})
        verdicts[category] = {"compatible": not rules, "detail": rules}
    return version, verdicts


def _graphql_inspector_run(case: Case) -> Tuple[str, Dict[str, Dict[str, Any]]]:
    """GraphQL-Inspector's ``diff`` over the two canonical SDL documents."""
    from app.graphql_diff import GRAPHQL_DIFF_TOOL_KEY, _sdl_of, run_graphql_diff

    version = _probe(GRAPHQL_DIFF_TOOL_KEY)
    base, head = canonical_models(case)
    result = _run(run_graphql_diff(_sdl_of(base.raw) or "", _sdl_of(head.raw) or ""))
    detail = sorted({f"{c.criticality}:{c.change_type}" for c in result.changes})
    return version, {DEFAULT_MODE: {"compatible": not result.has_breaking, "detail": detail}}


def _asyncapi_diff_run(case: Case) -> Tuple[str, Dict[str, Dict[str, Any]]]:
    """``@asyncapi/diff``'s standard ruleset over the two dereferenced documents.

    The tool has no modes; its verdict is compared with Apiome's default (``BACKWARD``). A diff
    with no breaking change but at least one ``unclassified`` one is inconclusive
    (``compatible: null``) and is not compared.
    """
    from app.asyncapi_diff import ASYNCAPI_DIFF_TOOL_KEY, run_asyncapi_diff

    version = _probe(ASYNCAPI_DIFF_TOOL_KEY)
    base, head = canonical_models(case)
    result = _run(run_asyncapi_diff(base.raw, head.raw))
    detail = sorted({f"{c.change_type}:{c.action}:{c.pointer}" for c in result.changes})
    compatible: Optional[bool] = False if result.has_breaking else (None if result.unclassified else True)
    return version, {MODE_BACKWARD: {"compatible": compatible, "detail": detail}}


