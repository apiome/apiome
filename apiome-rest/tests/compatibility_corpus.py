"""Cross-format compatibility golden corpus — shared machinery (XPC-4.6, #5750).

XPC-4.1–4.4 taught Apiome to grade Avro, JSON Schema, Protobuf and AsyncAPI changes by
compatibility mode (or ``buf breaking`` category), and GraphQL is graded against GraphQL-Inspector.
Those verdicts are only trustworthy while they agree with the tools Kafka, protobuf and GraphQL
teams already run. This corpus pins both sides:

``tests/golden/compatibility/<format>/<case>/``
    ``base.<ext>`` and ``head.<ext>`` — the two versions (``base/`` and ``head/`` directories of
    ``.proto`` files for Protobuf, so a type can move between files);
    ``expected.json`` — the case's hand-written ``description`` and ``source``, Apiome's verdict
    under every mode (``verdicts``, regenerated) and each reference tool's recorded verdict
    (``references``).

``tests/golden/compatibility/waivers.json``
    The documented, known differences: a ``(case, tool, mode)`` where Apiome deliberately reads a
    change differently from the reference tool, with the reason. It is rendered into the generated
    ``README.md`` and into the "Known differences from reference tools" section of
    ``apiome-docs/docs/govern/compatibility-modes.md``.

A **reference disagreement** is a ``(case, tool, mode)`` where the reference tool's verdict
(compatible or not) differs from Apiome's. It fails the build unless a waiver covers it; a waiver
that covers no disagreement is stale and fails too.

Reference tools are run **live** when they are installed (``buf``, ``graphql-inspector-diff``,
``asyncapi-diff``) or reachable (a Confluent-compatible registry API named by
:data:`APICURIO_URL_ENV` / :data:`CONFLUENT_URL_ENV`); the live answer must match the recording.
Without them the recorded verdicts are compared. With :data:`STRICT_ENV` set (CI does) a reference
tool that is not available fails instead of skipping.

**Regenerating.** ``pytest tests/test_compatibility_corpus_golden.py --update-golden`` (or
``UPDATE_COMPATIBILITY_GOLDENS=1``) rewrites every ``expected.json``'s ``verdicts``, re-records the
references of every tool available live (keeping the recorded answer of the others), prunes case
directories that no longer hold both sides, and rewrites the README and the docs section. Review the
diff before committing.
"""

