"""Generate ``src/app/data/discovery_v1_meta_schema.json`` — MFX-29.2 (#4174).

The Google API Discovery Service describes its own document format: the Discovery document of
``discovery/v1`` (https://www.googleapis.com/discovery/v1/apis/discovery/v1/rest) declares the schemas
``RestDescription``, ``RestResource``, ``RestMethod`` and ``JsonSchema``, which together *are* the
format a Discovery document follows. This script turns those four schemas into a JSON Schema draft-04
document (the Discovery metaschema the Discovery export is checked against, :mod:`app.discovery_validation`):

* the structure only — every ``description`` and ``enumDescriptions`` is left out;
* Discovery ``$ref: "Name"`` → ``{"$ref": "#/definitions/Name"}``; ``type: "any"`` → ``{}``; Discovery
  ``format`` values (``int64`` …) are left out, since draft-04 does not know them;
* then tightened with what the reference (https://developers.google.com/discovery/v1/reference/apis) and
  the type-and-format summary (https://developers.google.com/discovery/v1/type-format) document but the
  self-description does not declare: ``kind`` is ``discovery#restDescription``; the keys a document,
  method and parameter must have; ``type`` is one of the JSON Schema draft-03 types Discovery uses;
  ``location`` is ``path`` or ``query``; ``httpMethod`` is an upper-case verb.

Objects stay open (real Discovery documents carry keys the self-description does not list, such as
``mtlsRootUrl``): the published Discovery, Drive v3, Storage v1, YouTube v3, Calendar v3 and Sheets v4
documents all validate against it.

Usage (the downloaded document is data: pass its path, do not run anything from its folder)::

    cd apiome-rest && uv run python scripts/generate_discovery_meta_schema.py <path to discovery_v1_rest.json>
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path
from typing import Any, Dict

_OUT = Path(__file__).resolve().parents[1] / "src" / "app" / "data" / "discovery_v1_meta_schema.json"
_SCHEMAS = ("RestDescription", "RestResource", "RestMethod", "JsonSchema")
_SOURCE = "https://www.googleapis.com/discovery/v1/apis/discovery/v1/rest"
#: The JSON Schema draft-03 types Discovery uses (the type-and-format summary).
_TYPES = ["any", "array", "boolean", "integer", "number", "null", "object", "string"]


def _convert(schema: Any) -> Any:
    """One Discovery schema position → its draft-04 form (structure only)."""
    if not isinstance(schema, dict):
        return schema
    if "$ref" in schema:
        return {"$ref": f"#/definitions/{schema['$ref']}"}
    out: Dict[str, Any] = {}
    kind = schema.get("type")
    if kind and kind != "any":
        out["type"] = kind
    if "properties" in schema:
        out["properties"] = {name: _convert(sub) for name, sub in schema["properties"].items()}
    if "additionalProperties" in schema:
        out["additionalProperties"] = _convert(schema["additionalProperties"])
    if "items" in schema:
        out["items"] = _convert(schema["items"])
    if "enum" in schema:
        out["enum"] = list(schema["enum"])
    return out


def _tighten(definitions: Dict[str, Any]) -> None:
    """Add the rules the reference documents but the self-description does not declare."""
    description = definitions["RestDescription"]
    description["required"] = ["kind", "discoveryVersion", "id", "name", "version", "protocol", "rootUrl",
                               "servicePath"]
    properties = description["properties"]
    properties["kind"]["enum"] = ["discovery#restDescription"]
    properties["discoveryVersion"]["enum"] = ["v1"]
    properties["protocol"]["enum"] = ["rest"]
    # A document- or method-level parameter names its type and where it goes.
    parameter = {"allOf": [{"$ref": "#/definitions/JsonSchema"}, {"required": ["type", "location"]}]}
    properties["parameters"]["additionalProperties"] = parameter
    method = definitions["RestMethod"]
    method["required"] = ["id", "path", "httpMethod"]
    method["properties"]["httpMethod"]["pattern"] = "^[A-Z]+$"
    method["properties"]["parameters"]["additionalProperties"] = parameter
    for body in ("request", "response"):
        method["properties"][body]["required"] = ["$ref"]
    schema = definitions["JsonSchema"]["properties"]
    schema["type"]["enum"] = _TYPES
    schema["location"]["enum"] = ["path", "query"]


def build(source: Dict[str, Any]) -> Dict[str, Any]:
    """The metaschema for the Discovery self-description ``source``."""
    definitions = {name: _convert(source["schemas"][name]) for name in _SCHEMAS}
    _tighten(definitions)
    return {
        "$schema": "http://json-schema.org/draft-04/schema#",
        "id": "urn:apiome:discovery:v1:meta-schema",
        "title": "Google API Discovery document (v1)",
        "$comment": f"Generated by apiome-rest/scripts/generate_discovery_meta_schema.py from the structure of "
                    f"the RestDescription, RestResource, RestMethod and JsonSchema schemas at {_SOURCE} "
                    f"(revision {source.get('revision', 'unknown')}, read {date.today().isoformat()}), "
                    "tightened with the rules of the Discovery reference. Do not edit by hand.",
        "$ref": "#/definitions/RestDescription",
        "definitions": definitions,
    }


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-1].strip(), file=sys.stderr)
        return 2
    source = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    _OUT.write_text(json.dumps(build(source), indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
