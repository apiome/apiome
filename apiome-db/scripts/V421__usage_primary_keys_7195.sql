-- Primary keys for the usage rollup tables (DBP-1.12, #7195; see DBP-1.8, #7191).
--
-- usage_hourly and usage_daily (V290) have no primary key. Their identity is the nine-column
-- grain (tenant, project, source, environment, hour/day, revision, operation, status, consumer)
-- held by a UNIQUE NULLS NOT DISTINCT constraint, which cannot be promoted: version_record_id and
-- consumer_binding_id are nullable, and a primary key needs NOT NULL columns. Without a primary
-- key (or another replica identity) a logical-replication publication cannot carry the ingest
-- upserts or the retention deletes, and a single row has no short address.
--
-- Each table gets a bigint identity column as its primary key. The grain constraints are
-- unchanged, so the ingest upsert (ON CONFLICT ON CONSTRAINT usage_hourly_grain_uq) and the daily
-- rollup (apiome.rollup_usage_day) keep working; both name their columns, so the new column fills
-- itself. BY DEFAULT rather than ALWAYS so that a logical restore may carry ids over.
--
-- The legacy apiome.signup queue also has no primary key; V314 made it read-only (a trigger
-- refuses every write), so it is left as it is.
--
-- Large databases: adding an identity column rewrites each table under an ACCESS EXCLUSIVE lock
-- (usage ingest and usage reads wait; a few seconds per million rows), then builds the primary key
-- index. Schedule the upgrade outside peak ingest.
--
-- Rollback notes:
--   ALTER TABLE apiome.usage_hourly DROP COLUMN IF EXISTS id;
--   ALTER TABLE apiome.usage_daily DROP COLUMN IF EXISTS id;

ALTER TABLE apiome.usage_hourly
    ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE apiome.usage_daily
    ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'apiome.usage_hourly'::regclass AND contype = 'p') THEN
        ALTER TABLE apiome.usage_hourly ADD CONSTRAINT usage_hourly_pkey PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'apiome.usage_daily'::regclass AND contype = 'p') THEN
        ALTER TABLE apiome.usage_daily ADD CONSTRAINT usage_daily_pkey PRIMARY KEY (id);
    END IF;
END
$$;

COMMENT ON COLUMN apiome.usage_hourly.id IS
  'Surrogate primary key (DBP-1.12, #7195). The row''s identity is still the grain in usage_hourly_grain_uq.';

COMMENT ON COLUMN apiome.usage_daily.id IS
  'Surrogate primary key (DBP-1.12, #7195). The row''s identity is still the grain in usage_daily_grain_uq.';
