/**
 * Structural assertions over the DBP-1.12 (#7195) cleanup migrations:
 *
 *   - V419 drops redundant and unscanned indexes. Only non-unique indexes may go, and the one
 *     boolean / deleted_at index the purge sweep uses must stay.
 *   - V420 stores the importable predicate as a generated column and rebuilds the quality-sweep
 *     index on it (apiome-rest's test_repository_importable_json_schema.py pins the expression to
 *     REPOSITORY_FILE_IMPORTABLE_SQL).
 *   - V421 gives usage_hourly and usage_daily an identity primary key, idempotently.
 */

import fs from "node:fs/promises";
import path from "node:path";

import { beforeAll, describe, expect, it } from "vitest";

import { listMigrationFiles } from "../src/migrate.js";

const SCRIPTS_DIR = new URL("../scripts", import.meta.url).pathname;
const CLEANUP = "V419__redundant_index_cleanup_7195.sql";
const IMPORTABLE = "V420__repository_file_importable_column_7195.sql";
const USAGE_KEYS = "V421__usage_primary_keys_7195.sql";

/** A migration's statements, lower-cased, `--` comments stripped, whitespace collapsed. */
async function statementsOf(file: string): Promise<string[]> {
  const sql = await fs.readFile(path.join(SCRIPTS_DIR, file), "utf8");
  return sql
    .toLowerCase()
    .split("\n")
    .map((line) => line.split("--")[0])
    .join("\n")
    .split(/;\s*(?=\n|$)/)
    .map((statement) => statement.replace(/\s+/g, " ").trim())
    .filter(Boolean);
}

describe("DBP-1.12 cleanup migrations", () => {
  it("follow the foreign-key index migration in order", async () => {
    const files = await listMigrationFiles(SCRIPTS_DIR);
    const fk = files.indexOf("V418__foreign_key_indexes_7195.sql");
    expect(fk).toBeGreaterThan(-1);
    expect(files.indexOf(CLEANUP)).toBe(fk + 1);
    expect(files.indexOf(IMPORTABLE)).toBe(fk + 2);
    expect(files.indexOf(USAGE_KEYS)).toBe(fk + 3);
  });
});

describe("redundant index cleanup (V419)", () => {
  let statements: string[] = [];
  beforeAll(async () => {
    statements = await statementsOf(CLEANUP);
  });

  it("only drops indexes, idempotently", () => {
    for (const statement of statements) expect(statement).toMatch(/^drop index if exists apiome\.\w+$/);
  });

  it("drops 5 prefix indexes, 24 unscanned boolean / deleted_at indexes and the unused GIN", () => {
    const dropped = statements.map((statement) => statement.replace("drop index if exists apiome.", ""));
    expect(dropped).toHaveLength(30);
    expect(new Set(dropped).size).toBe(30);
    expect(dropped).toContain("idx_consumer_contract_pointers");
    expect(dropped).toContain("idx_versions_published");
  });

  it("never drops a constraint's index", () => {
    for (const statement of statements) expect(statement).not.toMatch(/(_pkey|_key|_unique|\.uq_\w+)$/);
  });

  it("keeps the deleted_at index the tenant purge sweep reads", () => {
    expect(statements.join(" ")).not.toContain("idx_tenants_deleted_at");
  });
});

describe("stored importable flag (V420)", () => {
  let statements: string[] = [];
  beforeAll(async () => {
    statements = await statementsOf(IMPORTABLE);
  });

  it("adds is_importable as a NOT NULL stored generated column", () => {
    const add = statements.find((statement) => statement.includes("add column if not exists is_importable"));
    expect(add).toMatch(/is_importable boolean not null generated always as \(coalesce\(.*, false\)\) stored$/);
  });

  it("replaces the quality-pending index with one that carries the importable predicate", () => {
    expect(statements).toContain("drop index if exists apiome.idx_tenant_repository_files_quality_pending");
    expect(statements).toContain(
      "create index if not exists idx_tenant_repository_files_quality_due on apiome.tenant_repository_files " +
        "(repository_id, path) where is_importable and blob_sha is not null and quality_scored_blob_sha is distinct from blob_sha",
    );
  });
});

describe("usage primary keys (V421)", () => {
  let sql = "";
  beforeAll(async () => {
    sql = (await statementsOf(USAGE_KEYS)).join(";\n");
  });

  it("adds a by-default identity id to both rollup tables", () => {
    for (const table of ["usage_hourly", "usage_daily"]) {
      expect(sql).toContain(`alter table apiome.${table} add column if not exists id bigint generated by default as identity`);
    }
  });

  it("adds each primary key only when the table has none", () => {
    for (const table of ["usage_hourly", "usage_daily"]) {
      expect(sql).toContain(`conrelid = 'apiome.${table}'::regclass and contype = 'p'`);
      expect(sql).toContain(`alter table apiome.${table} add constraint ${table}_pkey primary key (id)`);
    }
  });

  it("leaves the grain constraints the ingest upsert targets alone", () => {
    expect(sql).not.toMatch(/drop constraint|drop index|alter constraint/);
  });
});
