#!/usr/bin/env node
/**
 * Writes `lib/pact-ci-recipes.generated.ts` — the pipeline recipes the Contracts **Settings → CI and
 * commit statuses** tab shows (PFX-8.15, #7312) — from their sources, so the tab never drifts from
 * what is tested and documented:
 *
 *   GitHub Actions   the block after `# .github/workflows/pact.yml` in
 *                    `apiome-docs/docs/ship/pact-broker/ci-pact.mdx` ("Use the GitHub Action")
 *   GitLab CI        `pact-action/recipes/.gitlab-ci.yml`
 *   Jenkins          `pact-action/recipes/Jenkinsfile`
 *   Azure Pipelines  `pact-action/recipes/azure-pipelines.yml`
 *
 * The three files are smoke-tested against a stub CLI by `pact-action/tests/test_ci_recipes.sh`.
 * `tests/pact-ci-recipes.test.ts` fails while the generated file is stale.
 *
 *   node scripts/generate-pact-ci-recipes.mjs          # write
 *   node scripts/generate-pact-ci-recipes.mjs --check  # exit 1 when stale
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
export const OUTPUT = path.resolve(HERE, '..', 'lib', 'pact-ci-recipes.generated.ts');

/** The GitHub Actions block of the CI guide, without its fences. */
function githubRecipe() {
  const guide = fs.readFileSync(path.join(REPO, 'apiome-docs/docs/ship/pact-broker/ci-pact.mdx'), 'utf8');
  const start = guide.indexOf('# .github/workflows/pact.yml');
  if (start < 0) throw new Error('ci-pact.mdx has no "# .github/workflows/pact.yml" block');
  const end = guide.indexOf('```', start);
  return guide.slice(start, end).replace(/\n+$/, '\n');
}

/** One recipe file, as it is. */
function file(relative) {
  return fs.readFileSync(path.join(REPO, relative), 'utf8');
}

/** The module text. */
export function render() {
  const recipes = [
    { id: 'github', label: 'GitHub Actions', file: '.github/workflows/pact.yml', source: 'apiome-docs/docs/ship/pact-broker/ci-pact.mdx', text: githubRecipe() },
    { id: 'gitlab', label: 'GitLab CI', file: '.gitlab-ci.yml', source: 'pact-action/recipes/.gitlab-ci.yml', text: file('pact-action/recipes/.gitlab-ci.yml') },
    { id: 'jenkins', label: 'Jenkins', file: 'Jenkinsfile', source: 'pact-action/recipes/Jenkinsfile', text: file('pact-action/recipes/Jenkinsfile') },
    { id: 'azure', label: 'Azure Pipelines', file: 'azure-pipelines.yml', source: 'pact-action/recipes/azure-pipelines.yml', text: file('pact-action/recipes/azure-pipelines.yml') },
  ];
  return [
    '/**',
    ' * Generated by apiome-ui/scripts/generate-pact-ci-recipes.mjs — do not edit. The pipeline recipes of',
    ' * Contracts → Settings → CI and commit statuses (PFX-8.15, #7312), copied from their tested sources.',
    ' */',
    '',
    '/** One pipeline recipe. */',
    'export interface PactCiRecipe {',
    "  id: 'github' | 'gitlab' | 'jenkins' | 'azure';",
    '  label: string;',
    '  /** Where it goes in the repository. */',
    '  file: string;',
    '  /** Where it is copied from in the Apiome repository. */',
    '  source: string;',
    '  text: string;',
    '}',
    '',
    `export const PACT_CI_RECIPES: readonly PactCiRecipe[] = ${JSON.stringify(recipes, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== text) {
      console.error('lib/pact-ci-recipes.generated.ts is stale: run node scripts/generate-pact-ci-recipes.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, text);
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
  }
}
