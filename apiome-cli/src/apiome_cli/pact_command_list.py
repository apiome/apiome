"""
The ``apiome pact`` command list as JSON, for the CLI ↔ UI parity gate (PFX-8.2, #7299).

Every ``apiome pact`` command must have a screen in the Contracts workspace, and every Contracts
write screen must have a command. The UI's jest suite cannot import Typer, so this module renders
the command tree to ``apiome-cli/pact-commands.json`` (one entry per command: its name, summary,
positional arguments and option flags) and ``apiome-ui/tests/pact-parity-ledger.test.ts`` reads that
file beside ``docs/pact-parity-ledger.json``.

``tests/test_pact_command_list.py`` renders the list in memory and compares it with the committed
file, so a new command (or a renamed flag) fails CI until the file is regenerated — and the
regenerated file then fails the UI gate until the ledger has a row for it.

Regenerate from ``apiome-cli``::

    uv run python scripts/export_pact_commands.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import click
import typer

from apiome_cli.reference_doc import first_sentence, root_command

#: Where the list is committed, relative to the monorepo root.
PACT_COMMANDS_FILE = Path("apiome-cli/pact-commands.json")

#: The command that rewrites :data:`PACT_COMMANDS_FILE`.
REGENERATE_COMMAND = "cd apiome-cli && uv run python scripts/export_pact_commands.py"

#: The group the list describes.
GROUP = "pact"

#: Options every command has that say nothing about what it does.
_GENERIC_OPTIONS = frozenset({"--help"})


def _option_flags(command: click.Command) -> list[str]:
    """The long flags of a command's visible options, in declaration order.

    :param command: The command.
    :returns: e.g. ``["--consumer-app-version", "--branch"]``; ``--help`` is left out. An option
        with only a short flag is listed by that flag.
    """
    flags: list[str] = []
    for param in command.params:
        if not isinstance(param, click.Option) or getattr(param, "hidden", False):
            continue
        names = [name for name in param.opts if name.startswith("--")] or list(
            param.opts
        )
        name = names[0]
        if name not in _GENERIC_OPTIONS:
            flags.append(name)
    return flags


def _arguments(command: click.Command) -> list[str]:
    """The names of a command's positional arguments, in order.

    :param command: The command.
    :returns: e.g. ``["files"]``.
    """
    return [
        param.human_readable_name.lower()
        for param in command.params
        if isinstance(param, click.Argument) and not getattr(param, "hidden", False)
    ]


def pact_commands(app: typer.Typer | None = None) -> list[dict[str, Any]]:
    """Every visible ``apiome pact`` command, by name.

    :param app: A Typer app holding the ``pact`` group; defaults to :data:`apiome_cli.main.app`.
    :returns: One dict per command: ``name``, ``summary`` (first sentence of its help),
        ``arguments`` and ``options``.
    :raises LookupError: When the app has no ``pact`` group.
    """
    root = root_command(app)
    group = root.commands.get(GROUP)
    if not isinstance(group, click.Group):
        raise LookupError(f"the CLI has no `{GROUP}` command group")
    return [
        {
            "name": name,
            "summary": first_sentence(command.help),
            "arguments": _arguments(command),
            "options": _option_flags(command),
        }
        for name, command in _leaf_commands(group)
    ]


def _leaf_commands(group: click.Group, prefix: str = "") -> list[tuple[str, click.Command]]:
    """Every visible command under ``group``, a sub-group's as ``"<group> <command>"`` (PFX-8.14).

    :param group: The ``pact`` group, or one of its sub-groups.
    :param prefix: The sub-group path so far (``"retention "``).
    :returns: ``(name, command)`` pairs, sorted by name.
    """
    leaves: list[tuple[str, click.Command]] = []
    for name, command in sorted(group.commands.items()):
        if command.hidden:
            continue
        if isinstance(command, click.Group):
            leaves += _leaf_commands(command, f"{prefix}{name} ")
        else:
            leaves.append((f"{prefix}{name}", command))
    return leaves


def render_pact_commands(app: typer.Typer | None = None) -> str:
    """The committed file's content: stable, two-space indented JSON with a trailing newline.

    :param app: As for :func:`pact_commands`.
    :returns: The JSON text.
    """
    document = {
        "$comment": (
            "Generated by apiome-cli/scripts/export_pact_commands.py — do not edit. "
            "Read by apiome-ui/tests/pact-parity-ledger.test.ts against docs/pact-parity-ledger.json."
        ),
        "group": f"apiome {GROUP}",
        "commands": pact_commands(app),
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"
