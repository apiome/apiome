"""``apiome export sql`` and its output verbs — MFX-35.5 (#4315).

The SQL DDL export is one registry target (``sql-ddl``) with five outputs. The CLI offers it as
``apiome export sql`` (also ``sql-ddl`` / ``ddl``) and as ``apiome export dbml|prisma|liquibase|flyway``, which
preset ``--option output=<verb>``; every SQL verb takes ``--dialect postgres|mysql|ansi``. They run through the
generic export seam (``export <format> <artifact>``, MFX-8.1). These tests pin that the spellings resolve to the
``sql-ddl`` target, that the presets and ``--dialect`` reach the preview and the job, that a conflicting
``--option`` is a usage error, that a types-only export exits non-zero unless ``--force``, that ``--json`` prints
the tier, and that the export prints its fidelity **report** — the critical types-only advisory first.

The fixtures are recorded from the REST emitter registry: ``apiome-rest/tests/test_sql_ddl_target_card.py`` keeps
``export-targets-sql-ddl.json`` equal to the live descriptor, options schema and badge, and
``export-job-completed-sql-ddl-types-only.json`` equal to the Petstore export's live fidelity envelope and file.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from apiome_cli.client.export_registry import resolve_export_target
from apiome_cli.exit_codes import EXIT_ERROR, EXIT_SUCCESS, EXIT_USAGE
from apiome_cli.export_output import sort_report_items_worst_first
from apiome_cli.main import app
from helpers import strip_ansi

pytestmark = pytest.mark.usefixtures("api_key_env")

runner = CliRunner()

_FIXTURES = Path(__file__).resolve().parent / "fixtures"
_TARGETS = json.loads((_FIXTURES / "export-targets-sql-ddl.json").read_text())
_JOB = json.loads((_FIXTURES / "export-job-completed-sql-ddl-types-only.json").read_text())
_PREVIEW = json.loads((_FIXTURES / "export-preview-lossless.json").read_text())

_PROJECT_ID = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa"
_JOB_ID = "cccccccc-cccc-4ccc-8ccc-cccccccccccc"
_PROJECT = {"id": _PROJECT_ID, "name": "Pet Store", "slug": "pet-store", "enabled": True}
_BASE = "http://localhost:8000"
_TARGETS_URL = f"{_BASE}/v1/export/acme-corp/targets?artifact={_PROJECT_ID}&version=1.0.0"
_JOBS_URL = f"{_BASE}/v1/export/acme-corp/jobs"
_SQL_NAME = _JOB["result"]["files"][0]["path"]
_SQL_TEXT = '-- Pet Store: SQL DDL (postgres), generated by Apiome.\nCREATE TABLE pet (\n  id BIGINT\n);\n'


@pytest.fixture
def api_key_env(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("APIOME_API_KEY", "test-key")
    monkeypatch.setenv("APIOME_BASE_URL", _BASE)
    monkeypatch.setenv("APIOME_TENANT_ID", "acme-corp")


def _mock_export(httpx_mock: object) -> None:
    """Serve one export: project lookup, targets, preview, job start, job status and the script download."""
    httpx_mock.add_response(url=f"{_BASE}/v1/projects/acme-corp/by-slug/pet-store", json=_PROJECT)
    httpx_mock.add_response(url=_TARGETS_URL, json=_TARGETS)
    httpx_mock.add_response(url=f"{_BASE}/v1/export/acme-corp/preview", method="POST", json=_PREVIEW)
    httpx_mock.add_response(url=_JOBS_URL, method="POST", status_code=202,
                            json={"job_id": _JOB_ID, "status_path": f"/v1/export/acme-corp/jobs/{_JOB_ID}"})
    httpx_mock.add_response(url=f"{_JOBS_URL}/{_JOB_ID}", json=_JOB)
    httpx_mock.add_response(url=f"{_JOBS_URL}/{_JOB_ID}/download", content=_SQL_TEXT.encode("utf-8"),
                            headers={"Content-Type": "application/json",
                                     "Content-Disposition": f'attachment; filename="{_SQL_NAME}"'})


def _posted(httpx_mock: object, suffix: str) -> dict:
    request = next(r for r in httpx_mock.get_requests() if r.url.path.endswith(suffix) and r.method == "POST")
    return json.loads(request.content)


def _args(out: str, *extra: str, verb: str = "sql") -> list[str]:
    return ["export", verb, "pet-store", "--version", "1.0.0", "--out", out, "--poll-interval", "0.1", *extra]


@pytest.mark.parametrize("spelling", ["sql", "SQL", "sql-ddl", "ddl", "dbml", "prisma", "liquibase", "flyway"])
def test_every_sql_verb_resolves_to_the_sql_ddl_target(spelling: str) -> None:
    assert resolve_export_target(spelling, _TARGETS["targets"]) == "sql-ddl"


def test_the_fixture_carries_every_output_and_dialect_and_the_types_only_badge() -> None:
    target = _TARGETS["targets"][0]
    assert target["descriptor"]["label"] == "SQL DDL" and target["descriptor"]["paradigm"] == "data_schema"
    properties = target["options_schema"]["properties"]
    assert set(properties["output"]["enum"]) == {"ddl", "dbml", "prisma", "liquibase", "flyway"}
    assert set(properties["dialect"]["enum"]) == {"postgres", "mysql", "ansi"}
    assert target["default_options"]["output"] == "ddl" and target["default_options"]["dialect"] == "postgres"
    assert target["fidelity"]["tier"] == "types-only"


def test_the_job_report_starts_with_the_critical_types_only_advisory() -> None:
    items = _JOB["result"]["fidelity"]["report"]["items"]
    advisory = next(item for item in items if item.get("target_mapping") == "types-only")
    assert advisory["severity"] == "critical" and advisory["kind"] == "drop"


@pytest.mark.parametrize(("verb", "extra", "expected"), [
    ("sql", ["--dialect", "mysql"], {"dialect": "mysql"}),
    ("sql", [], {}),
    ("dbml", [], {"output": "dbml"}),
    ("prisma", ["--dialect", "postgres"], {"output": "prisma", "dialect": "postgres"}),
    ("liquibase", ["--dialect", "ansi"], {"output": "liquibase", "dialect": "ansi"}),
    ("flyway", ["--option", "nested=tables"], {"output": "flyway", "nested": "tables"}),
    ("dbml", ["--option", "output=dbml"], {"output": "dbml"}),
])
def test_the_verb_and_dialect_reach_the_preview_and_the_job(
    httpx_mock: object, tmp_path: Path, verb: str, extra: list[str], expected: dict
) -> None:
    _mock_export(httpx_mock)
    result = runner.invoke(app, _args(str(tmp_path / _SQL_NAME), "--force", *extra, verb=verb))
    assert result.exit_code == EXIT_SUCCESS, result.output
    # No options at all are sent as none, not as an empty object.
    assert (_posted(httpx_mock, "/preview").get("options") or {}) == expected
    job = _posted(httpx_mock, "/jobs")
    assert (job["target"], job.get("options") or {}) == ("sql-ddl", expected)


@pytest.mark.parametrize(("verb", "extra", "message"), [
    ("dbml", ["--option", "output=prisma"], "writes output=dbml"),
    ("sql", ["--dialect", "mysql", "--option", "dialect=ansi"], "Give the dialect once"),
])
def test_a_conflicting_option_is_a_usage_error(verb: str, extra: list[str], message: str, tmp_path: Path) -> None:
    result = runner.invoke(app, _args(str(tmp_path / _SQL_NAME), *extra, verb=verb))
    assert result.exit_code == EXIT_USAGE and message in strip_ansi(result.stderr)


def test_an_unknown_dialect_is_rejected(tmp_path: Path) -> None:
    result = runner.invoke(app, _args(str(tmp_path / _SQL_NAME), "--dialect", "oracle"))
    assert result.exit_code != EXIT_SUCCESS and "oracle" in strip_ansi(result.output)


def test_a_types_only_export_exits_nonzero_without_force(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    out = tmp_path / _SQL_NAME
    result = runner.invoke(app, _args(str(out)))
    assert result.exit_code == EXIT_ERROR, result.output
    # The file is still written: the exit code only flags the loss.
    assert out.read_text(encoding="utf-8") == _SQL_TEXT
    assert "types-only" in strip_ansi(result.stderr)


def test_json_mode_prints_the_metadata_with_the_tier(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    result = runner.invoke(app, ["--json", *_args(str(tmp_path / _SQL_NAME), "--force")])
    assert result.exit_code == EXIT_SUCCESS, result.output
    payload = json.loads(result.stdout.strip())
    assert payload["fidelity_target"] == "sql-ddl" and payload["fidelity"]["status"] == "types-only"


@pytest.mark.parametrize("verb", ["sql", "dbml", "prisma", "liquibase", "flyway"])
def test_every_sql_verb_has_the_dialect_flag(verb: str) -> None:
    result = runner.invoke(app, ["export", verb, "--help"])
    assert result.exit_code == EXIT_SUCCESS and "--dialect" in strip_ansi(result.output)


def test_another_verb_has_no_dialect_flag() -> None:
    assert "--dialect" not in strip_ansi(runner.invoke(app, ["export", "openrpc", "--help"]).output)


def test_the_export_prints_its_fidelity_report_worst_losses_first(httpx_mock: object, tmp_path: Path) -> None:
    """The acceptance criterion: the CLI exports with report — the summary and the worst losses."""
    report = _JOB["result"]["fidelity"]["report"]["items"]
    worst = next(item for item in sort_report_items_worst_first(report) if item["kind"] != "ok")
    _mock_export(httpx_mock)
    result = runner.invoke(app, _args(str(tmp_path / _SQL_NAME), "--force"))
    assert result.exit_code == EXIT_SUCCESS, result.output
    stderr = strip_ansi(result.stderr)
    summary = _JOB["result"]["fidelity"]["summary"]
    assert f"({summary['preserved_percent']}% preserved)" in stderr
    assert "Per-construct losses:" in stderr and worst["construct"] in stderr
