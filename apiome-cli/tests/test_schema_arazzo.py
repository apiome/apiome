"""Tests for ``apiome schema arazzo <tenant>/<project>/<version>`` (CLI 9.6, #3249).

The fixtures under ``tests/fixtures/schema_arazzo/`` were generated by apiome-rest's own
``arazzo_generator`` (two classes, Charge and Refund, in acme-corp/payments-api/2.1.0), so the
command is exercised against the documents the server actually serves.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from apiome_cli.exit_codes import (
    EXIT_CHECKSUM_MISMATCH,
    EXIT_ERROR,
    EXIT_SUCCESS,
    EXIT_USAGE,
)
from apiome_cli.main import app
from apiome_cli.published_spec import (
    PublishedRef,
    normalize_expected_sha256,
    parse_published_ref,
    parse_serialization,
    published_document_path,
    sha256_hex,
)

runner = CliRunner()

_HOST = "http://localhost:8000"
_FULL_URL = f"{_HOST}/v1/arazzo/acme-corp/payments-api/2.1.0"
_CHARGE_URL = f"{_FULL_URL}/Charge"
_FIXTURES = Path(__file__).parent / "fixtures" / "schema_arazzo"
_FULL_YAML = (_FIXTURES / "payments.arazzo.yaml").read_bytes()
_FULL_JSON = (_FIXTURES / "payments.arazzo.json").read_bytes()
_CHARGE_YAML = (_FIXTURES / "charge.arazzo.yaml").read_bytes()
_REF = "acme-corp/payments-api/2.1.0"


@pytest.fixture(autouse=True)
def base_url_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Point the CLI at the mocked host with no API key or tenant (public browse routes)."""
    monkeypatch.setenv("APIOME_BASE_URL", _HOST)
    monkeypatch.delenv("APIOME_API_KEY", raising=False)
    monkeypatch.delenv("APIOME_TENANT_ID", raising=False)


def _yaml_response(httpx_mock: object, url: str = _FULL_URL, body: bytes = _FULL_YAML) -> None:
    httpx_mock.add_response(
        url=url,
        match_headers={"Accept": "application/yaml"},
        content=body,
        headers={"Content-Type": "application/x-yaml"},
    )


# --- helpers -------------------------------------------------------------------------------


def test_parse_published_ref_splits_three_slugs() -> None:
    """A tenant/project/version ref splits into its three slugs, whitespace-stripped."""
    assert parse_published_ref(" acme-corp/payments-api/v2.1.0 ") == PublishedRef(
        "acme-corp", "payments-api", "v2.1.0"
    )


@pytest.mark.parametrize("text", ["acme-corp/payments-api", "a/b/c/d", "a//c", "/b/c", ""])
def test_parse_published_ref_rejects_other_shapes(text: str) -> None:
    """Anything but exactly three non-empty parts is a usage error."""
    with pytest.raises(ValueError, match="<tenant>/<project>/<version>"):
        parse_published_ref(text)


@pytest.mark.parametrize(("value", "expected"), [("json", "json"), ("YAML", "yaml"), ("yml", "yaml")])
def test_parse_serialization(value: str, expected: str) -> None:
    """--format accepts json, yaml and yml in any case."""
    assert parse_serialization(value) == expected


def test_parse_serialization_rejects_other_values() -> None:
    """--format openapi is not a serialization."""
    with pytest.raises(ValueError, match="json or yaml"):
        parse_serialization("openapi")


def test_normalize_expected_sha256_accepts_prefix_and_case() -> None:
    """The sha256: prefix the summary prints, and upper case, are accepted."""
    digest = "ab" * 32
    assert normalize_expected_sha256(f"SHA256:{digest.upper()}") == digest


@pytest.mark.parametrize("value", ["abc", "zz" * 32, "ab" * 33])
def test_normalize_expected_sha256_rejects_non_digests(value: str) -> None:
    """Values that are not 64 hex characters are a usage error."""
    with pytest.raises(ValueError, match="64-character hex"):
        normalize_expected_sha256(value)


def test_published_document_path_quotes_segments() -> None:
    """Every segment, including the class name, is URL-quoted."""
    ref = PublishedRef("acme-corp", "payments-api", "2.1.0")
    assert published_document_path("arazzo", ref) == "/v1/arazzo/acme-corp/payments-api/2.1.0"
    assert published_document_path("arazzo", ref, "Line Item/x") == (
        "/v1/arazzo/acme-corp/payments-api/2.1.0/Line%20Item%2Fx"
    )


# --- command -------------------------------------------------------------------------------


def test_default_is_yaml_to_stdout(httpx_mock: object) -> None:
    """With no flags the full bundle is requested as YAML and written verbatim to stdout."""
    _yaml_response(httpx_mock)
    result = runner.invoke(app, ["schema", "arazzo", _REF])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _FULL_YAML
    assert f"sha256:{hashlib.sha256(_FULL_YAML).hexdigest()}" in result.stderr


def test_format_json_requests_json(httpx_mock: object) -> None:
    """--format json asks for JSON and writes the server's bytes unchanged."""
    httpx_mock.add_response(url=_FULL_URL, match_headers={"Accept": "application/json"}, content=_FULL_JSON)
    result = runner.invoke(app, ["schema", "arazzo", _REF, "--format", "json"])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert json.loads(result.stdout_bytes)["arazzo"] == "1.0.1"
    assert result.stdout_bytes == _FULL_JSON


def test_class_uses_per_class_route(httpx_mock: object) -> None:
    """--class fetches /v1/arazzo/.../{class} and gets only that class's workflow."""
    _yaml_response(httpx_mock, url=_CHARGE_URL, body=_CHARGE_YAML)
    result = runner.invoke(app, ["schema", "arazzo", _REF, "--class", "Charge"])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _CHARGE_YAML
    assert b"workflowId: chargeWorkflow" in result.stdout_bytes
    assert b"refundWorkflow" not in result.stdout_bytes


def test_output_writes_file_and_human_summary(httpx_mock: object, tmp_path: Path) -> None:
    """--output writes the file; the summary on stderr names bytes, format and checksum."""
    _yaml_response(httpx_mock)
    out = tmp_path / "workflows.arazzo.yaml"
    result = runner.invoke(app, ["schema", "arazzo", _REF, "--output", str(out)])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert out.read_bytes() == _FULL_YAML
    assert result.stdout == ""
    assert f"Wrote {len(_FULL_YAML)} bytes to {out}" in result.stderr
    assert "Format: arazzo" in result.stderr
    assert "Serialization: yaml" in result.stderr


def test_json_metadata_on_stdout_when_writing_a_file(httpx_mock: object, tmp_path: Path) -> None:
    """Global --json prints one metadata object on stdout when the document goes to a file."""
    _yaml_response(httpx_mock)
    out = tmp_path / "w.yaml"
    result = runner.invoke(app, ["--json", "schema", "arazzo", _REF, "-o", str(out)])
    assert result.exit_code == EXIT_SUCCESS, result.output
    meta = json.loads(result.stdout)
    assert meta == {
        "output": str(out),
        "bytes_written": len(_FULL_YAML),
        "content_type": "application/x-yaml",
        "checksum": f"sha256:{sha256_hex(_FULL_YAML)}",
        "format": "arazzo",
        "serialization": "yaml",
    }


def test_json_metadata_on_stderr_when_writing_stdout(httpx_mock: object) -> None:
    """With the document on stdout, --json metadata moves to stderr so stdout stays byte-safe."""
    _yaml_response(httpx_mock)
    result = runner.invoke(app, ["--json", "schema", "arazzo", _REF])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _FULL_YAML
    assert json.loads(result.stderr.strip().splitlines()[-1])["checksum"].startswith("sha256:")


def test_expect_sha256_match_writes(httpx_mock: object, tmp_path: Path) -> None:
    """A matching --expect-sha256 writes the document as usual."""
    _yaml_response(httpx_mock)
    out = tmp_path / "w.yaml"
    digest = hashlib.sha256(_FULL_YAML).hexdigest()
    result = runner.invoke(app, ["schema", "arazzo", _REF, "-o", str(out), "--expect-sha256", digest])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert out.read_bytes() == _FULL_YAML


def test_expect_sha256_mismatch_exits_6_and_writes_nothing(httpx_mock: object, tmp_path: Path) -> None:
    """A different digest exits 6, names both digests, and leaves no file behind."""
    _yaml_response(httpx_mock)
    out = tmp_path / "w.yaml"
    wrong = "0" * 64
    result = runner.invoke(app, ["schema", "arazzo", _REF, "-o", str(out), "--expect-sha256", wrong])
    assert result.exit_code == EXIT_CHECKSUM_MISMATCH
    assert not out.exists()
    assert f"expected {wrong}, got {sha256_hex(_FULL_YAML)}" in result.stderr
    assert "Nothing was written." in result.stderr


def test_expect_sha256_mismatch_on_stdout_prints_nothing(httpx_mock: object) -> None:
    """On a mismatch, nothing reaches stdout either, so a `> file` redirect stays empty."""
    _yaml_response(httpx_mock)
    result = runner.invoke(app, ["schema", "arazzo", _REF, "--expect-sha256", "f" * 64])
    assert result.exit_code == EXIT_CHECKSUM_MISMATCH
    assert result.stdout_bytes == b""


@pytest.mark.parametrize(
    "args",
    [
        ["acme-corp/payments-api"],
        [_REF, "--format", "xml"],
        [_REF, "--expect-sha256", "nope"],
        [_REF, "--class", "  "],
        [_REF, "--output", " "],
    ],
)
def test_usage_errors_exit_2_without_a_request(httpx_mock: object, args: list[str]) -> None:
    """Bad refs, formats, digests, class names and outputs exit 2 before any HTTP call."""
    result = runner.invoke(app, ["schema", "arazzo", *args])
    assert result.exit_code == EXIT_USAGE
    assert httpx_mock.get_requests() == []


@pytest.mark.parametrize(
    ("status", "detail", "code"),
    [
        (404, "Version not found: acme-corp/payments-api/2.1.0", EXIT_USAGE),
        (403, "This version is not published", EXIT_USAGE),
        (500, "boom", EXIT_ERROR),
    ],
)
def test_api_errors_map_to_exit_codes(httpx_mock: object, status: int, detail: str, code: int) -> None:
    """4xx (unknown, unpublished, private) exits 2; a 5xx exits 1; nothing is written."""
    httpx_mock.add_response(url=_FULL_URL, status_code=status, json={"detail": detail})
    result = runner.invoke(app, ["schema", "arazzo", _REF])
    assert result.exit_code == code
    assert result.stdout_bytes == b""


def test_unknown_class_exits_2(httpx_mock: object) -> None:
    """An unknown --class is the per-class route's 404, exit 2."""
    httpx_mock.add_response(url=f"{_FULL_URL}/Nope", status_code=404, json={"detail": "Class not found: Nope"})
    result = runner.invoke(app, ["schema", "arazzo", _REF, "--class", "Nope"])
    assert result.exit_code == EXIT_USAGE
    assert "Class not found: Nope" in result.stderr


def test_api_key_is_sent_for_private_versions(httpx_mock: object, monkeypatch: pytest.MonkeyPatch) -> None:
    """A configured API key goes out as X-API-Key; no tenant configuration is needed."""
    monkeypatch.setenv("APIOME_API_KEY", "obj_test_key")
    httpx_mock.add_response(
        url=_FULL_URL,
        match_headers={"X-API-Key": "obj_test_key", "Accept": "application/yaml"},
        content=_FULL_YAML,
    )
    result = runner.invoke(app, ["schema", "arazzo", _REF])
    assert result.exit_code == EXIT_SUCCESS, result.output
