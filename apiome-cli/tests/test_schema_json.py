"""Tests for ``apiome schema json <tenant>/<project>/<version>`` (CLI 9.7, #3250).

The fixtures under ``tests/fixtures/schema_json/`` were generated by apiome-rest's own
``jsonschema_generator`` (classes Charge and Refund in acme-corp/payments-api/2.1.0). The flag
handling is shared with ``schema arazzo`` (``_download_published``) and the helpers are covered
in ``test_schema_arazzo.py``; these tests pin what differs (route, default format, ``format``
in the summary) and the pipe-into-code-gen contract.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from apiome_cli.exit_codes import EXIT_CHECKSUM_MISMATCH, EXIT_SUCCESS, EXIT_USAGE
from apiome_cli.main import app
from apiome_cli.published_spec import sha256_hex

runner = CliRunner()

_HOST = "http://localhost:8000"
_FULL_URL = f"{_HOST}/v1/json/acme-corp/payments-api/2.1.0"
_CHARGE_URL = f"{_FULL_URL}/Charge"
_FIXTURES = Path(__file__).parent / "fixtures" / "schema_json"
_FULL_JSON = (_FIXTURES / "payments.schema.json").read_bytes()
_FULL_YAML = (_FIXTURES / "payments.schema.yaml").read_bytes()
_CHARGE_JSON = (_FIXTURES / "charge.schema.json").read_bytes()
_REF = "acme-corp/payments-api/2.1.0"


@pytest.fixture(autouse=True)
def base_url_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Point the CLI at the mocked host with no API key or tenant (public browse routes)."""
    monkeypatch.setenv("APIOME_BASE_URL", _HOST)
    monkeypatch.delenv("APIOME_API_KEY", raising=False)
    monkeypatch.delenv("APIOME_TENANT_ID", raising=False)


def _json_response(httpx_mock: object, url: str = _FULL_URL, body: bytes = _FULL_JSON) -> None:
    httpx_mock.add_response(
        url=url,
        match_headers={"Accept": "application/json"},
        content=body,
        headers={"Content-Type": "application/json"},
    )


def test_default_is_json_to_stdout_only(httpx_mock: object) -> None:
    """With no flags the bundle is requested as JSON; stdout carries only the document bytes."""
    _json_response(httpx_mock)
    result = runner.invoke(app, ["schema", "json", _REF])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _FULL_JSON
    assert json.loads(result.stdout_bytes)["$schema"] == "https://json-schema.org/draft/2020-12/schema"
    assert "Format: json-schema" in result.stderr
    assert f"Checksum: sha256:{sha256_hex(_FULL_JSON)}" in result.stderr


def test_class_streams_the_per_class_schema(httpx_mock: object) -> None:
    """--class fetches /v1/json/.../{class}: one schema a code generator can read as-is."""
    _json_response(httpx_mock, url=_CHARGE_URL, body=_CHARGE_JSON)
    result = runner.invoke(app, ["schema", "json", _REF, "--class", "Charge"])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _CHARGE_JSON
    schema = json.loads(result.stdout_bytes)
    assert schema["title"] == "Charge"
    assert schema["required"] == ["amount"]


def test_format_yaml_requests_yaml(httpx_mock: object) -> None:
    """--format yaml asks for YAML through Accept and writes the server's bytes unchanged."""
    httpx_mock.add_response(url=_FULL_URL, match_headers={"Accept": "application/yaml"}, content=_FULL_YAML)
    result = runner.invoke(app, ["schema", "json", _REF, "--format", "yaml"])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert result.stdout_bytes == _FULL_YAML


def test_output_file_with_json_metadata(httpx_mock: object, tmp_path: Path) -> None:
    """-o writes the file; global --json prints the summary object (format json-schema) on stdout."""
    _json_response(httpx_mock)
    out = tmp_path / "schema.json"
    result = runner.invoke(app, ["--json", "schema", "json", _REF, "-o", str(out)])
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert out.read_bytes() == _FULL_JSON
    meta = json.loads(result.stdout)
    assert meta["format"] == "json-schema"
    assert meta["serialization"] == "json"
    assert meta["checksum"] == f"sha256:{sha256_hex(_FULL_JSON)}"
    assert meta["bytes_written"] == len(_FULL_JSON)


def test_expect_sha256_match_and_mismatch(httpx_mock: object, tmp_path: Path) -> None:
    """A matching digest writes; a different one exits 6 and writes nothing."""
    httpx_mock.add_response(url=_FULL_URL, content=_FULL_JSON, is_reusable=True)
    good, bad = tmp_path / "good.json", tmp_path / "bad.json"
    ok = runner.invoke(app, ["schema", "json", _REF, "-o", str(good), "--expect-sha256", sha256_hex(_FULL_JSON)])
    assert ok.exit_code == EXIT_SUCCESS, ok.output
    assert good.read_bytes() == _FULL_JSON
    refused = runner.invoke(app, ["schema", "json", _REF, "-o", str(bad), "--expect-sha256", "1" * 64])
    assert refused.exit_code == EXIT_CHECKSUM_MISMATCH
    assert not bad.exists()


def test_unknown_class_exits_2(httpx_mock: object) -> None:
    """An unknown --class is the per-class route's 404, exit 2, with nothing on stdout."""
    httpx_mock.add_response(url=f"{_FULL_URL}/Nope", status_code=404, json={"detail": "Class not found: Nope"})
    result = runner.invoke(app, ["schema", "json", _REF, "--class", "Nope"])
    assert result.exit_code == EXIT_USAGE
    assert result.stdout_bytes == b""
    assert "Class not found: Nope" in result.stderr


def test_bad_ref_exits_2_without_a_request(httpx_mock: object) -> None:
    """A ref without three parts is a usage error before any HTTP call."""
    result = runner.invoke(app, ["schema", "json", "acme-corp/payments-api"])
    assert result.exit_code == EXIT_USAGE
    assert httpx_mock.get_requests() == []
