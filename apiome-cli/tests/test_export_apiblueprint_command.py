"""``apiome export apiblueprint`` — MFX-18.4 (#3908).

The API Blueprint document (Markdown + MSON, a human-readable documentation export) is a registry target
(``apiblueprint``), so the verb runs through the generic export seam (``export <format> <artifact>``, MFX-8.1)
with no command code of its own. These tests pin that the spelling resolves, that the options
(``include_comments`` as a boolean, ``media_type`` and ``format_version`` as strings) reach the preview and the
job, that the one ``.apib`` file is written to ``--out``, that ``--json`` prints the tier, that a lossy export
exits non-zero unless ``--force``, and that the constraints MSON cannot express are printed as dropped.

The fixtures are recorded from the REST emitter registry: ``apiome-rest/tests/test_apiblueprint_target_card.py``
keeps ``export-targets-apiblueprint.json`` equal to the live descriptor, options schema and badge, and
``export-job-completed-apiblueprint-lossy.json`` equal to the Petstore export's live fidelity (with its report)
and file name.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from apiome_cli.client.export_registry import resolve_export_target
from apiome_cli.exit_codes import EXIT_ERROR, EXIT_SUCCESS
from apiome_cli.main import app
from helpers import strip_ansi

pytestmark = pytest.mark.usefixtures("api_key_env")

runner = CliRunner()

_FIXTURES = Path(__file__).resolve().parent / "fixtures"
_TARGETS = json.loads((_FIXTURES / "export-targets-apiblueprint.json").read_text())
_JOB = json.loads((_FIXTURES / "export-job-completed-apiblueprint-lossy.json").read_text())
_PREVIEW = json.loads((_FIXTURES / "export-preview-lossless.json").read_text())

_PROJECT_ID = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa"
_JOB_ID = "cccccccc-cccc-4ccc-8ccc-cccccccccccc"
_PROJECT = {"id": _PROJECT_ID, "name": "Pet Store", "slug": "pet-store", "enabled": True}
_BASE = "http://localhost:8000"
_TARGETS_URL = f"{_BASE}/v1/export/acme-corp/targets?artifact={_PROJECT_ID}&version=1.0.0"
_JOBS_URL = f"{_BASE}/v1/export/acme-corp/jobs"
_APIB_NAME = _JOB["result"]["files"][0]["path"]
_APIB_TEXT = "FORMAT: 1A\n\n# Pet Store\n\n<!-- Generated by Apiome from Pet Store -->\n\n## Pets [/pets]\n"
_MSON_CONSTRAINT_DROP = "MSON has no validation facets"


@pytest.fixture
def api_key_env(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("APIOME_API_KEY", "test-key")
    monkeypatch.setenv("APIOME_BASE_URL", _BASE)
    monkeypatch.setenv("APIOME_TENANT_ID", "acme-corp")


def _mock_export(httpx_mock: object, job: dict = _JOB) -> None:
    """Serve one export: project lookup, targets, preview, job start, job status and the ``.apib`` download."""
    httpx_mock.add_response(url=f"{_BASE}/v1/projects/acme-corp/by-slug/pet-store", json=_PROJECT)
    httpx_mock.add_response(url=_TARGETS_URL, json=_TARGETS)
    httpx_mock.add_response(url=f"{_BASE}/v1/export/acme-corp/preview", method="POST", json=_PREVIEW)
    httpx_mock.add_response(url=_JOBS_URL, method="POST", status_code=202,
                            json={"job_id": _JOB_ID, "status_path": f"/v1/export/acme-corp/jobs/{_JOB_ID}"})
    httpx_mock.add_response(url=f"{_JOBS_URL}/{_JOB_ID}", json=job)
    httpx_mock.add_response(url=f"{_JOBS_URL}/{_JOB_ID}/download", content=_APIB_TEXT.encode("utf-8"),
                            headers={"Content-Type": "text/markdown",
                                     "Content-Disposition": f'attachment; filename="{_APIB_NAME}"'})


def _posted(httpx_mock: object, suffix: str) -> dict:
    request = next(r for r in httpx_mock.get_requests() if r.url.path.endswith(suffix) and r.method == "POST")
    return json.loads(request.content)


def _args(out: str, *extra: str) -> list[str]:
    return ["export", "apiblueprint", "pet-store", "--version", "1.0.0", "--out", out, "--poll-interval", "0.1", *extra]


@pytest.mark.parametrize("spelling", ["apiblueprint", "APIBlueprint"])
def test_the_spelling_resolves_to_the_apiblueprint_target(spelling: str) -> None:
    assert resolve_export_target(spelling, _TARGETS["targets"]) == "apiblueprint"


def test_the_fixture_carries_the_options_and_the_lossy_badge() -> None:
    target = _TARGETS["targets"][0]
    assert set(target["options_schema"]["properties"]) == {"format_version", "include_comments", "media_type"}
    assert target["default_options"] == {"format_version": "1A", "include_comments": True,
                                       "media_type": "application/json"}
    assert target["descriptor"]["multi_file"] is False
    assert target["fidelity"]["tier"] == "lossy"


def test_a_lossy_export_exits_nonzero_without_force(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    out = tmp_path / "petstore.apib"
    result = runner.invoke(app, _args(str(out)))
    assert result.exit_code == EXIT_ERROR, result.output
    # The file is still written: the exit code only flags the loss.
    assert out.read_text(encoding="utf-8") == _APIB_TEXT
    assert "lossy" in strip_ansi(result.stderr)


def test_the_constraints_mson_cannot_express_are_printed_as_dropped(httpx_mock: object, tmp_path: Path) -> None:
    """The Petstore's formats and bounds have no MSON form: the report drops them, and the CLI prints it."""
    drops = [item for item in _JOB["result"]["fidelity"]["report"]["items"]
             if item["kind"] == "drop" and _MSON_CONSTRAINT_DROP in item["message"]]
    assert drops
    _mock_export(httpx_mock)
    result = runner.invoke(app, _args(str(tmp_path / "petstore.apib"), "--force"))
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert _MSON_CONSTRAINT_DROP in strip_ansi(result.stderr)


def test_force_writes_the_apib_file(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    out = tmp_path / "petstore.apib"
    result = runner.invoke(app, _args(str(out), "--force"))
    assert result.exit_code == EXIT_SUCCESS, result.output
    assert out.read_text(encoding="utf-8") == _APIB_TEXT


def test_the_options_reach_the_preview_and_the_job(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    result = runner.invoke(app, _args(str(tmp_path / "petstore.apib"), "--force",
                                      "--option", "include_comments=false", "--option", "media_type=application/xml",
                                      "--option", "format_version=1A"))
    assert result.exit_code == EXIT_SUCCESS, result.output
    expected = {"include_comments": False, "media_type": "application/xml", "format_version": "1A"}
    assert _posted(httpx_mock, "/preview")["options"] == expected
    job = _posted(httpx_mock, "/jobs")
    assert (job["target"], job["options"]) == ("apiblueprint", expected)


def test_json_mode_prints_the_metadata_with_the_tier(httpx_mock: object, tmp_path: Path) -> None:
    _mock_export(httpx_mock)
    result = runner.invoke(app, ["--json", *_args(str(tmp_path / "petstore.apib"), "--force")])
    assert result.exit_code == EXIT_SUCCESS, result.output
    payload = json.loads(result.stdout.strip())
    assert (payload["format"], payload["fidelity_target"]) == ("apiblueprint", "apiblueprint")
    assert payload["fidelity"]["status"] == "lossy"


def test_export_targets_lists_apiblueprint_with_its_tier(httpx_mock: object) -> None:
    httpx_mock.add_response(url=f"{_BASE}/v1/projects/acme-corp/by-slug/pet-store", json=_PROJECT)
    httpx_mock.add_response(url=_TARGETS_URL, json=_TARGETS)
    result = runner.invoke(app, ["--json", "export", "targets", "--project", "pet-store", "--version", "1.0.0"])
    assert result.exit_code == EXIT_SUCCESS, result.output
    payload = json.loads(result.stdout)
    rows = payload["targets"] if isinstance(payload, dict) else payload
    assert next(r for r in rows if r["descriptor"]["key"] == "apiblueprint")["fidelity"]["tier"] == "lossy"


def test_the_verb_has_help() -> None:
    result = runner.invoke(app, ["export", "apiblueprint", "--help"])
    assert result.exit_code == EXIT_SUCCESS
    output = strip_ansi(result.output)
    assert "Export an artifact to 'apiblueprint'" in output and "--option" in output
